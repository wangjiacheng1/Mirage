package com.mirage.engine.prompt

/**
 * 写在所有卡设定最前面的通用叙事要求。
 *
 * ## 为什么需要它
 *
 * 不加这一段时，模型默认把自己当「助手」：回答简短、爱做点评、
 * 容易把用户那句话当成已经发生的事而只写后续。角色卡里通常只写
 * 「这个角色是谁」，很少写「该怎么写」，于是这块是空的。
 *
 * ## 为什么不写死字数
 *
 * 「每次至少写 300 字」这种要求会让模型在没内容的时候硬凑，
 * 反而更难看。给原则（篇幅跟着剧情走）比给数字更管用。
 *
 * ## 它和卡的关系
 *
 * 这段放在**最前面**，卡的设定接在后面。顺序决定了优先级：
 * 后面的内容更具体、更贴近这张卡，和这里冲突时以卡为准。
 * 所以这里只写最通用的几条，不碰具体风格 —— 风格是卡作者的事。
 */
object NarrativePreset {

    /**
     * 默认的通用叙事要求。
     *
     * 四条各自解决一个具体问题：
     * 一、改掉「我是助手」的默认身份，不然它会点评、会总结、会写得很短；
     * 二、用户那句话是「这一轮要演什么」，不是「已经演完的事」——
     *     不说清楚的话，你写「我推开门」，它会直接从门后开始写；
     * 三、别的角色该有自己的反应，可以拒绝、可以打断，否则所有人都在顺着你说；
     * 四、每轮要往前走，不要把上一段换个说法再写一遍。
     */
    const val DEFAULT: String = """你在续写一个故事。只输出故事正文，不要解释、不要点评、不要总结，篇幅跟着剧情需要走。

- 你负责叙述场景，并扮演除玩家之外的所有角色。
- 玩家发来的内容是这一轮要演出的方向，不是已经发生过的事；要把这个过程演出来，而不是跳过它直接写结果。
- 其他角色按各自的性格反应，可以迟疑、拒绝、反问或打断，不必总是顺着玩家。
- 每一轮都要让剧情往前走，不要把已经写过的情节换个说法重来一遍。"""
}
