def flatten(obj, prefix=""):
    """把嵌套 dict 压成 JSON Pointer -> value。数组整体作为一个叶子。"""
    out = {}
    for k, v in obj.items():
        path = prefix + "/" + k
        if isinstance(v, dict):
            out.update(flatten(v, path))
        else:
            out[path] = v
    return out


def type_name(v):
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, (int, float)):
        return "number"
    if isinstance(v, list):
        return "array"
    return "string"


